"use strict";
// Generates the fictional seed dataset: TOTAL stores in dist/stores.csv and
// the matching D1 reseed migration. All names and coordinates are synthetic
// (template combinations around real station locations) — nothing is copied
// from real store directories, so the dataset carries no third-party data
// license. Deterministic: mulberry32 with a fixed seed, so re-running
// reproduces the exact same dataset.
import { readFileSync, writeFileSync } from "node:fs";
import { STATIONS, STATION_POINTS } from "./src/store-validation.mjs";

const TOTAL = 11000;
const AREAS = {"札幌":"札幌市中央区","旭川":"旭川市","仙台":"仙台市青葉区","盛岡":"盛岡市","秋田":"秋田市","山形":"山形市","福島":"福島市","宇都宮":"宇都宮市","高崎":"高崎市","新潟":"新潟市中央区","長野":"長野市","金沢":"金沢市","秋葉原":"千代田区","御徒町":"台東区","上野":"台東区","東京":"千代田区","新宿":"新宿区","渋谷":"渋谷区","池袋":"豊島区","横浜":"横浜市西区","川崎":"川崎市川崎区","千葉":"千葉市中央区","大宮":"さいたま市大宮区","静岡":"静岡市葵区","名古屋":"名古屋市中村区","京都":"京都市下京区","大阪":"大阪市北区","難波":"大阪市中央区","神戸":"神戸市中央区","岡山":"岡山市北区","広島":"広島市南区","松山":"松山市","高知":"高知市","博多":"福岡市博多区","小倉":"北九州市小倉北区","熊本":"熊本市西区","鹿児島中央":"鹿児島市","那覇":"那覇市"};
const TOKYO = new Set(["秋葉原", "御徒町", "上野", "東京", "新宿", "渋谷", "池袋"]);

function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rand = mulberry32(20261127);

// Existing hand-written rows stay as the first entries (ids renumbered to
// the 5-digit scheme); the rest is generated.
const csvPath = new URL("./dist/stores.csv", import.meta.url);
const [, ...lines] = readFileSync(csvPath, "utf8").trim().split(/\r?\n/);
const rows = lines.map((line, i) => {
  const [id, name, station, area, type, lon, lat] = line.split(",");
  return { id: String(i + 1).padStart(5, "0"), name, station, area, type, lon: Number(lon), lat: Number(lat) };
});

const cores = ["カード", "トレカ", "デュエル", "ホビー", "ゲーム", "コレクション", "パック", "デッキ"];
const suffixes = ["工房", "スタンド", "ベース", "ラボ", "マーケット", "キオスク", "アトリエ", "ライブラリ", "ガレージ", "デスク", "ラウンジ", "テラス", "ボックス", "売店", "書架", "堂", "店", "本舗", "屋", "城"];
const mods = ["", "駅前", "中央", "東", "西", "南", "北", "新"];
const places = ["隠れ家", "基地", "集会所", "横丁", "小径"];
function namePool(st) {
  const pool = [];
  for (const m of mods) for (const c of cores) for (const s of suffixes) pool.push(m + st + c + s);
  for (const c of cores) for (const s of suffixes) pool.push(c + s + " " + st);
  for (const c of cores) for (const p of places) pool.push(st + c + "の" + p);
  // Deterministic shuffle.
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool;
}

// Weighted distribution: Tokyo stations get double weight.
const weights = STATIONS.map((st) => (TOKYO.has(st) ? 2 : 1));
const totalWeight = weights.reduce((a, b) => a + b, 0);
const remaining = TOTAL - rows.length;
const counts = weights.map((w) => Math.floor((remaining * w) / totalWeight));
while (counts.reduce((a, b) => a + b, 0) < remaining) {
  counts[counts.indexOf(Math.max(...counts))] += 1;
}

const usedNames = new Set(rows.map((r) => r.name));
let n = rows.length;
STATIONS.forEach((st, si) => {
  const pool = namePool(st);
  const [slat, slon] = STATION_POINTS[st];
  let pi = 0;
  for (let k = 0; k < counts[si]; k++) {
    let name = pool[pi++];
    while (usedNames.has(name)) name = pool[pi++];
    usedNames.add(name);
    n += 1;
    const type = n % 10 < 6 ? "shop" : n % 10 < 8 ? "play" : "retail";
    const lat = Number((slat + (rand() * 2 - 1) * 0.045).toFixed(4));
    const lon = Number((slon + (rand() * 2 - 1) * 0.055).toFixed(4));
    rows.push({ id: String(n).padStart(5, "0"), name, station: st, area: AREAS[st], type, lon, lat });
  }
});
if (rows.length !== TOTAL) throw new Error("row count " + rows.length);

const esc = (s) => String(s).replaceAll("'", "''");
writeFileSync(csvPath, "id,name,station,area,type,lon,lat\n" + rows.map((r) => [r.id, r.name, r.station, r.area, r.type, r.lon, r.lat].join(",")).join("\n") + "\n");

const batches = [];
for (let i = 0; i < rows.length; i += 200) {
  const vals = rows.slice(i, i + 200).map((r) =>
    `('${r.id}','${esc(r.name)}','${esc(r.station)}','${esc(r.area)}','${r.type}',${r.lat},${r.lon},'2026-11-27T00:00:00.000Z',NULL)`).join(",\n");
  batches.push("INSERT INTO stores (id, name, station, area, type, lat, lon, updated_at, updated_by) VALUES\n" + vals + ";");
}
writeFileSync(new URL("./migrations/0003_seed_11000.sql", import.meta.url),
  "-- Reseed with the generated fictional dataset (11,000 stores nationwide).\n" +
  "-- Generated by generate-stores.mjs; dist/stores.csv is the source form.\n" +
  "DELETE FROM stores;\n" + batches.join("\n") + "\n");

const groups = new Set(rows.map((r) => r.lon + "," + r.lat)).size;
console.log(JSON.stringify({ total: rows.length, stations: STATIONS.length, coordGroups: groups }));
