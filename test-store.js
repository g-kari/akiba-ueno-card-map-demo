"use strict";
const assert=require("node:assert/strict"),spec=require("./dist/store-data.js"),seed=require("./dist/stores.json");
assert.equal(spec.validateRows(seed).length,11000);
assert.deepEqual(spec.parse(spec.encode(seed)),seed);
assert.deepEqual(spec.parse(spec.encode([])),[]);
assert.equal(spec.nextId(seed),"11001");
assert.equal(spec.nextId(seed.slice(1)),"00001");
assert.throws(()=>spec.validateRows([seed[0],seed[0]]),/店舗ID/);
assert.throws(()=>spec.validate({...seed[0],name:"  "}),/店舗名/);
assert.throws(()=>spec.validate({...seed[0],lat:""}),/緯度/);
assert.throws(()=>spec.validate({...seed[0],lon:false}),/経度/);
assert.throws(()=>spec.validate({...seed[0],lat:50}),/緯度/);
assert.throws(()=>spec.validate({...seed[0],type:"__proto__"}),/店舗タイプ/);
assert.throws(()=>spec.parse('{"version":2,"stores":[]}'),/JSON/);
assert.equal(new URL(spec.links(seed[0]).place).searchParams.get("query"),"35.7002,139.7708");
assert.equal(new URL(spec.links(seed[0]).directions).searchParams.get("travelmode"),"walking");
assert.equal(spec.groups(seed).length,10994);
assert.deepEqual(spec.groups([seed[0],{...seed[0],id:"99999"}]).map(g=>g.length),[2]);
console.log("16 checks passed");
